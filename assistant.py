def _norm(s):
    return re.sub(r"\s+", "", (s or "").lower())


def _kb_answer(q: str):
    ql = _norm(q)
    scored = []
    for topic, keys, ans in _KB:
        hit = sum(len(k) for k in keys if _norm(k) in ql)
        if hit:
            scored.append((hit, topic, ans))
    if not scored:
        return _FALLBACK
    scored.sort(reverse=True)
    ans = scored[0][2]
    # 附上其他相關主題建議
    related = [t for _, t, _ in scored[1:4]]
    if related:
        ans += "\n\n💡 也可以問:" + "、".join(related)
    return ans


def _llm_answer(q: str, key: str, history=None) -> str:
    import anthropic
    client = anthropic.Anthropic(api_key=key)
    # 把對話歷史(最近 10 則)轉成 Claude 格式,實現多輪對話
    messages = []
    for m in (history or [])[-10:]:
        role = "assistant" if m.get("role") == "assistant" else "user"
        messages.append({"role": role, "content": m.get("text", "")})
    messages.append({"role": "user", "content": q})
    msg = client.messages.create(model=_MODEL, max_tokens=800,
                                 system=_SYSTEM, messages=messages)
    return "".join(getattr(b, "text", "") for b in msg.content) or _kb_answer(q)



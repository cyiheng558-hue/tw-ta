def _kb_answer(q: str) -> str:
    ql = q.lower()
    best, best_hits = None, 0
    for keys, ans in _KB:
        hits = sum(1 for k in keys if k.lower() in ql)
        if hits > best_hits:
            best, best_hits = ans, hits
    return best if best else _FALLBACK


def _llm_answer(q: str, key: str) -> str:
    import anthropic
    client = anthropic.Anthropic(api_key=key)
    msg = client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=500,
        system=_SYSTEM,
        messages=[{"role": "user", "content": q}],
    )
    return "".join(b.text for b in msg.content if getattr(b, "type", "") == "text")


def answer(q: str) -> str:
    """回答一個問題。有設 ANTHROPIC_API_KEY 就用 Claude,否則用內建知識庫。"""
    q = (q or "").strip()
    if not q:
        return _FALLBACK
    key = os.environ.get("ANTHROPIC_API_KEY")
    if key:
        try:
            return _llm_answer(q, key)
        except Exception:
            pass  # 失敗就退回知識庫
    return _kb_answer(q)


